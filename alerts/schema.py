"""
Centralized alert and replay-run database schemas for PostgreSQL and SQLite.

Aligns PostgreSQL schema types (`source_ip`/`initiator_ip` as TEXT so both
IPv4/IPv6 addresses and network-wide sentinel identifiers such as "__NETWORK__"
are valid), defines relational `replay_runs` and `replay_run_alerts` foreign-key
tables, indexes, and idempotent migration/rollback statements.
"""

from typing import Dict, List


POSTGRES_ALERTS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_ip TEXT NOT NULL,
    attack_type VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    confidence DOUBLE PRECISION NOT NULL,
    first_seen DOUBLE PRECISION NOT NULL,
    last_seen DOUBLE PRECISION NOT NULL,
    resolved_at DOUBLE PRECISION,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    event_count INTEGER NOT NULL DEFAULT 1,
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    initiator_ip TEXT,
    responder_ips JSONB NOT NULL DEFAULT '[]'::jsonb,
    related_flows JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
""".strip()

POSTGRES_REPLAY_RUNS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS replay_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pcap_file TEXT NOT NULL,
    alert_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
""".strip()

POSTGRES_REPLAY_RUN_ALERTS_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS replay_run_alerts (
    run_id BIGINT NOT NULL REFERENCES replay_runs(run_id) ON DELETE CASCADE,
    alert_id BIGINT NOT NULL REFERENCES alerts(alert_id) ON DELETE CASCADE,
    PRIMARY KEY (run_id, alert_id)
);
""".strip()

POSTGRES_SCHEMA_STATEMENTS = (
    POSTGRES_ALERTS_TABLE_SQL,
    POSTGRES_REPLAY_RUNS_TABLE_SQL,
    POSTGRES_REPLAY_RUN_ALERTS_TABLE_SQL,
)

POSTGRES_INDEX_STATEMENTS = (
    "CREATE INDEX IF NOT EXISTS idx_alerts_status ON alerts(status);",
    "CREATE INDEX IF NOT EXISTS idx_alerts_source_ip ON alerts(source_ip);",
    "CREATE INDEX IF NOT EXISTS idx_alerts_attack_type ON alerts(attack_type);",
    "CREATE INDEX IF NOT EXISTS idx_alerts_first_seen ON alerts(first_seen);",
    "CREATE INDEX IF NOT EXISTS idx_alerts_active_lookup ON alerts(status, source_ip, attack_type);",
    "CREATE INDEX IF NOT EXISTS idx_replay_runs_pcap_run_id ON replay_runs(pcap_file, run_id DESC);",
    "CREATE INDEX IF NOT EXISTS idx_replay_runs_created_at ON replay_runs(created_at DESC);",
    "CREATE INDEX IF NOT EXISTS idx_replay_run_alerts_alert_id ON replay_run_alerts(alert_id);",
)

POSTGRES_ALIGN_IP_COLUMNS_SQL = """
ALTER TABLE alerts
    ALTER COLUMN source_ip TYPE TEXT USING host(source_ip),
    ALTER COLUMN initiator_ip TYPE TEXT USING CASE
        WHEN initiator_ip IS NULL THEN NULL
        ELSE host(initiator_ip)
    END;
""".strip()

POSTGRES_ALIGN_EXTENDED_COLUMNS_SQL = (
    "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS initiator_ip TEXT;",
    "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS responder_ips JSONB NOT NULL DEFAULT '[]'::jsonb;",
    "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS related_flows JSONB NOT NULL DEFAULT '[]'::jsonb;",
)

POSTGRES_ROLLBACK_IP_COLUMNS_SQL = """
ALTER TABLE alerts
    ALTER COLUMN source_ip TYPE INET USING source_ip::inet,
    ALTER COLUMN initiator_ip TYPE INET USING CASE
        WHEN initiator_ip IS NULL THEN NULL
        ELSE initiator_ip::inet
    END;
""".strip()

POSTGRES_ROLLBACK_INDEXES_SQL = (
    "DROP INDEX IF EXISTS idx_replay_run_alerts_alert_id;",
    "DROP INDEX IF EXISTS idx_replay_runs_created_at;",
    "DROP INDEX IF EXISTS idx_replay_runs_pcap_run_id;",
    "DROP INDEX IF EXISTS idx_alerts_active_lookup;",
)

POSTGRES_ROLLBACK_REPLAY_SCHEMA_SQL = (
    "DROP TABLE IF EXISTS replay_run_alerts;",
    "DROP TABLE IF EXISTS replay_runs;",
)


def build_postgres_rollback_sql() -> str:
    """
    Build a transactional PostgreSQL rollback script for Phase 2A changes.

    WARNING: Converting TEXT back to INET fails with InvalidTextRepresentation if
    any non-IP sentinel rows (such as '__NETWORK__') have been inserted. Restore a
    verified pg_dump -Fc backup instead of performing an unsafe partial rollback.
    """
    lines = [
        "-- =============================================================================",
        "-- MONI Phase 2A Rollback Script (PostgreSQL)",
        "--",
        "-- WARNING: Do NOT run this DDL blindly if '__NETWORK__' or other non-IP rows",
        "-- exist in alerts.source_ip or alerts.initiator_ip; casting TEXT to INET will",
        "-- fail cleanly with InvalidTextRepresentation inside the transaction below.",
        "-- Never delete or modify sentinel rows automatically just to force a rollback.",
        "--",
        "-- RECOMMENDED RECOVERY: Restore your verified pg_dump custom-format backup",
        "-- in a quiesced database (after stopping API and collector writers) instead",
        "-- of attempting an unsafe partial DDL rollback.",
        "-- =============================================================================",
        "BEGIN;",
        "",
        "-- 1. Drop dependent Phase 2A indexes",
        *POSTGRES_ROLLBACK_INDEXES_SQL,
        "",
        "-- 2. Drop FK child table replay_run_alerts BEFORE parent replay_runs",
        *POSTGRES_ROLLBACK_REPLAY_SCHEMA_SQL,
        "",
        "-- 3. Revert source_ip / initiator_ip TEXT -> INET (fails if '__NETWORK__' exists)",
        POSTGRES_ROLLBACK_IP_COLUMNS_SQL,
        "",
        "COMMIT;",
    ]
    return "\n".join(lines)

POSTGRES_SEQUENCE_SYNC_STATEMENTS = (
    "SELECT setval(pg_get_serial_sequence('alerts', 'alert_id'), COALESCE((SELECT MAX(alert_id) FROM alerts), 0) + 1, false);",
    "SELECT setval(pg_get_serial_sequence('replay_runs', 'run_id'), COALESCE((SELECT MAX(run_id) FROM replay_runs), 0) + 1, false);",
)


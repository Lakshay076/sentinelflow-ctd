        self.assertIn("ALTER COLUMN initiator_ip TYPE TEXT USING CASE", joined)
        self.assertIn("CREATE TABLE IF NOT EXISTS replay_runs", joined)
        self.assertIn("CREATE TABLE IF NOT EXISTS replay_run_alerts", joined)
        self.assertIn("CREATE INDEX IF NOT EXISTS idx_replay_runs_pcap_run_id", joined)


class _FakePostgresCursor:
    """Minimal stateful mock cursor recording SQL statements and returning scripted rows."""

    def __init__(self, fetchone_results=None, fetchall_results=None, conn=None):
        self.executed = []
        self._fetchone_results = list(fetchone_results or [])
        self._fetchall_results = list(fetchall_results or [])
        self._conn = conn

    def execute(self, query, params=None):
        normalized = " ".join(str(query).split())
        if self._conn is not None and getattr(self._conn, "read_only", False):
            first_word = normalized.lstrip("(").split(None, 1)[0].upper()
            if first_word not in {"SELECT", "SHOW", "EXPLAIN"}:
                raise RuntimeError(f"cannot execute {first_word} in a read-only transaction")
        self.executed.append((normalized, params))

    def fetchone(self):
        if self._fetchone_results:
            return self._fetchone_results.pop(0)
        return (1,)

    def fetchall(self):
        if self._fetchall_results:
            return self._fetchall_results.pop(0)
        return []

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        return False


class _FakePostgresConnection:
    def __init__(self, cursor):
        self._cursor = cursor
        self._cursor._conn = self
        self.committed = 0
        self.read_only = False
        self.cursor_opened_with_read_only = []

    def cursor(self):
        self.cursor_opened_with_read_only.append(self.read_only)
        return self._cursor

    def commit(self):
        if self.read_only:
            raise RuntimeError("cannot commit in a read-only mode test guard")
        self.committed += 1

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        return False



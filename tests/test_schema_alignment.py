    def test_destructive_operations_never_fallback_or_modify_sqlite_on_postgres_failure(self):
        from telemetry.live_metrics import LiveMetricsStore

        sqlite_alerts_db = os.path.join(self._tmpdir.name, "preserved_alerts.db")
        sqlite_metrics_db = os.path.join(self._tmpdir.name, "preserved_metrics.db")

        # Seed isolated SQLite databases to prove destructive PG errors leave SQLite intact
        seed_alerts = AlertStore(db_path=sqlite_alerts_db, env_file=None)
        a_active = seed_alerts.create("10.0.0.10", "PORT_SCAN", "HIGH", 0.9, 100.0, ["scan"])
        a_resolved = seed_alerts.create("10.0.0.11", "SYN_FLOOD", "HIGH", 0.9, 101.0, ["syn"])
        seed_alerts.resolve(a_resolved.alert_id, timestamp=105.0)
        seed_alerts.record_replay_run("demo.pcap", [a_active.alert_id, a_resolved.alert_id], timestamp=106.0)

        seed_metrics = LiveMetricsStore(db_path=sqlite_metrics_db, env_file=None)
        seed_metrics.add_window({"packets": 42, "bytes": 4200, "window_duration": 1.0}, timestamp=200.0)

        init_conn = _FakePostgresConnection(_FakePostgresCursor())
        with patch.dict(
            os.environ,
            {
                "DATABASE_URL": "postgresql://ctd_user:TestPass!@localhost:5432/ctd",
                "CTD_DB_BACKEND": "auto",
                "CTD_DB_STRICT": "false",
            },
            clear=False,
        ):
            with patch(
                "psycopg.connect",
                side_effect=[
                    init_conn,
                    psycopg.errors.ConnectionFailure("08006 lost connection during clear_all"),
                    psycopg.errors.ConnectionFailure("08006 lost connection during clear_history"),
                ],
            ):
                pg_alerts = AlertStore(env_file=None)
                pg_alerts.db_path = sqlite_alerts_db
                self.assertTrue(pg_alerts.use_postgres)

                with self.assertRaises(DatabaseConnectionError):
                    pg_alerts.clear_all()
                self.assertTrue(pg_alerts.use_postgres)

                with self.assertRaises(DatabaseConnectionError):
                    pg_alerts.clear_history()
                self.assertTrue(pg_alerts.use_postgres)

            with patch(
                "psycopg.connect",
                side_effect=[
                    init_conn,
                    psycopg.errors.ConnectionFailure("08006 lost connection during clear"),
                ],
            ):
                pg_metrics = LiveMetricsStore(env_file=None)
                pg_metrics.db_path = sqlite_metrics_db
                self.assertTrue(pg_metrics.use_postgres)

                with self.assertRaises(DatabaseConnectionError):
                    pg_metrics.clear()
                self.assertTrue(pg_metrics.use_postgres)

        # Verify SQLite records were NOT modified or deleted
        verify_alerts = AlertStore(db_path=sqlite_alerts_db, env_file=None)
        self.assertEqual(len(verify_alerts.all()), 2)
        self.assertEqual(len(verify_alerts.active()), 1)
        self.assertEqual(len(verify_alerts.resolved()), 1)
        self.assertIsNotNone(verify_alerts.get_latest_replay_run("demo.pcap"))

        verify_metrics = LiveMetricsStore(db_path=sqlite_metrics_db, env_file=None)
        self.assertEqual(verify_metrics.latest()["packets"], 42)

        # Explicit SQLite selection still allows clear_all/clear_history normally
        self.assertEqual(verify_alerts.clear_history(), 1)
        self.assertEqual(verify_alerts.clear_all(), 1)
        self.assertEqual(verify_alerts.all(), [])
        verify_metrics.clear()
        self.assertIsNone(verify_metrics.latest())


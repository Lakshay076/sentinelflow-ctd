def inspect_postgres_schema(cursor) -> Dict[str, Dict[str, str]]:
    """Inspect existing public-schema alert and replay tables without mutating data."""
    cursor.execute(
        """
        SELECT table_name, column_name, data_type
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name IN ('alerts', 'replay_runs', 'replay_run_alerts')
        ORDER BY table_name, ordinal_position;
        """
    )
    tables: Dict[str, Dict[str, str]] = {}
    for table_name, column_name, data_type in cursor.fetchall():
        tables.setdefault(str(table_name), {})[str(column_name)] = str(data_type).lower()
    return tables


def plan_postgres_schema_alignment(schema_info: Dict[str, Dict[str, str]]) -> List[str]:
    """
    Build the exact ordered list of idempotent SQL statements required to align
    a PostgreSQL database to the current MONI schema without touching rows.
    """
    statements: List[str] = []
    alert_cols = schema_info.get("alerts")

    if not alert_cols:
        statements.append(POSTGRES_ALERTS_TABLE_SQL)
    else:
        for stmt in POSTGRES_ALIGN_EXTENDED_COLUMNS_SQL:
            col_name = stmt.split("EXISTS ")[1].split()[0]
            if col_name not in alert_cols:
                statements.append(stmt)

        ip_alters = []
        if alert_cols.get("source_ip") == "inet":
            ip_alters.append("ALTER COLUMN source_ip TYPE TEXT USING host(source_ip)")
        if alert_cols.get("initiator_ip") == "inet":
            ip_alters.append(
                "ALTER COLUMN initiator_ip TYPE TEXT USING CASE "
                "WHEN initiator_ip IS NULL THEN NULL ELSE host(initiator_ip) END"
            )
        if ip_alters:
            statements.append("ALTER TABLE alerts\n    " + ",\n    ".join(ip_alters) + ";")

    if "replay_runs" not in schema_info:
        statements.append(POSTGRES_REPLAY_RUNS_TABLE_SQL)
    if "replay_run_alerts" not in schema_info:
        statements.append(POSTGRES_REPLAY_RUN_ALERTS_TABLE_SQL)

    statements.extend(POSTGRES_INDEX_STATEMENTS)
    return statements


def apply_postgres_schema_alignment(cursor, execute: bool = True) -> List[str]:
    """Inspect and optionally execute idempotent PostgreSQL schema alignment."""
    schema_info = inspect_postgres_schema(cursor)
    statements = plan_postgres_schema_alignment(schema_info)
    if execute:
        for stmt in statements:
            cursor.execute(stmt)
    return statements
